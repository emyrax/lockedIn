export default function GearDecoration({ size = 'medium', color = 'var(--emerald)', className = '', style = {} }) {
  const ref = useRef(null);
  const paths = gearSvgs[size] || gearSvgs.medium;

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const durs = paths.map(() => 8 + Math.random() * 10);
    const dirs = paths.map(() => Math.random() > 0.5 ? 1 : -1);
    let raf;
    let start = performance.now();
    const animate = (now) => {
      const t = (now - start) / 1000;
      paths.forEach((_, i) => {
        const child = el.children[i];
        if (child) {
          const rot = (t / durs[i]) * 360 * dirs[i];
          child.style.transform = `rotate(${rot}deg)`;
        }
      });
      raf = requestAnimationFrame(animate);
    };
    raf = requestAnimationFrame(animate);
    return () => cancelAnimationFrame(raf);
  }, [paths]);

  const dims = { small: 40, medium: 64, large: 96, xl: 160, xxl: 240 }[size] || 64;

  return (
    <div ref={ref} className={`gear-decoration ${className}`} style={{ position: 'relative', width: dims, height: dims, ...style }}>
      {paths.map((path, i) => {
        const s = 0.5 + Math.random() * 0.5;
        const dim = dims * s;
        const offset = (dims - dim) / 2;
        return (
          <svg key={i} width={dim} height={dim} viewBox="0 0 24 24" fill={color}
            style={{
              position: 'absolute', top: offset, left: offset, opacity: 0.15 + (i === 0 ? 0.2 : 0),
              transformOrigin: 'center',
            }}
          >
            <path d={path} />
          </svg>
        );
      })}
    </div>
  );
}
